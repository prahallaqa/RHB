package practicequestions;

public class Converting_int_byte {
	public static void main(String[] args) {
		int a = 10;
		byte b = (byte) a;
		System.out.println(b);

		byte c = 20;
		int d = c;
		System.out.println(d);

		float e = 123;
		double f = e;
		System.out.println(f);

		double g = 10.45;
		byte h = (byte) g;
		System.out.println(h);
	}
}
